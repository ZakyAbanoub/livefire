#!/usr/bin/env node
// livefire build — assemble the UNIVERSAL Workflow script the Workflow tool launches directly.
//
// Output: dist/livefire.workflow.js  — ONE script for every stack. It contains the adapter
// contract (src/adapter.js) + the pipeline (src/harness-core.js), but NO preset: the controller
// (src/detect.js) resolves the adapter from presets/ and passes it in as `cfg.adapter` at
// launch. So adding a stack is "add presets/<x>.js + register it in presets/index.js" — no
// rebuild per preset.
//
// Why a build at all: the Workflow runtime loads one script that must begin with
// `export const meta`. The source stays modular (import/export); the build inlines the adapter
// contract, strips ES import/export, and hoists `export const meta` to the top.
//
// Usage: node build.mjs

import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(fileURLToPath(import.meta.url))

function stripModule(src) {
  return src
    .split('\n')
    .filter((line) => !/^\s*import\s.+\sfrom\s.+$/.test(line))
    .map((line) => line.replace(/^export\s+(const|let|var|function|class|async)\b/, '$1'))
    .join('\n')
}

function section(name, body) {
  return `\n// ════════════════════════ inlined: ${name} ════════════════════════\n${body.trim()}\n`
}

const pgInvSrc = await readFile(join(ROOT, 'src/inventory.js'), 'utf8')
const adapterSrc = await readFile(join(ROOT, 'src/adapter.js'), 'utf8')
const coreSrc = await readFile(join(ROOT, 'src/harness-core.js'), 'utf8')
const rulesSrc = await readFile(join(ROOT, 'src/prover-rules.js'), 'utf8')
const budgetSrc = await readFile(join(ROOT, 'src/budget.js'), 'utf8')
const invViewSrc = await readFile(join(ROOT, 'src/inventory-view.js'), 'utf8')

const metaMatch = coreSrc.match(/\/\/#META-START[^\n]*\n([\s\S]*?)\n\/\/#META-END/)
const bodyMatch = coreSrc.match(/\/\/#BODY-START[^\n]*\n([\s\S]*)$/)
if (!metaMatch || !bodyMatch) throw new Error('harness-core.js is missing //#META-START…//#META-END or //#BODY-START markers')

const metaBlock = metaMatch[1].trim() // `export const meta = {...}` — kept verbatim, first statement
const coreBody = stripModule(bodyMatch[1])
const pgInvBody = stripModule(pgInvSrc) // must precede adapter (adapter imports it)
const adapterBody = stripModule(adapterSrc)

// Inline the FULL preset registry so the controller can pass a small `cfg.preset` string
// instead of the whole adapter object (large args get dropped in Workflow transit). Order:
// adapter (defines GENERIC_ADAPTER) → every preset (define <x>Adapter, use GENERIC_ADAPTER) →
// index (defines REGISTRY from them) → core body (reads REGISTRY). Skip TEMPLATE (stub, unregistered).
const presetDir = join(ROOT, 'presets')
const presetFiles = (await readdir(presetDir)).filter((f) => f.endsWith('.js') && f !== 'index.js' && f !== 'TEMPLATE.js').sort()
const presetBodies = []
for (const f of presetFiles) presetBodies.push(section(`presets/${f}`, stripModule(await readFile(join(presetDir, f), 'utf8'))))
const indexBody = stripModule(await readFile(join(presetDir, 'index.js'), 'utf8'))

const header = `// livefire — ASSEMBLED universal workflow. DO NOT EDIT BY HAND.
// Generated by build.mjs from src/adapter.js + src/budget.js + src/inventory-view.js + presets/* + src/harness-core.js.
// The full preset REGISTRY is inlined; the controller passes a small cfg.preset string.
// Edit the sources and re-run \`node build.mjs\`.
`

const out = [
  header,
  metaBlock,
  section('src/inventory.js', pgInvBody),
  section('src/adapter.js', adapterBody),
  section('src/prover-rules.js', stripModule(rulesSrc)),
  section('src/budget.js', stripModule(budgetSrc)),
  section('src/inventory-view.js', stripModule(invViewSrc)),
  ...presetBodies,
  section('presets/index.js', indexBody),
  section('src/harness-core.js (body)', coreBody),
].join('\n')

await mkdir(join(ROOT, 'dist'), { recursive: true })
const outPath = join(ROOT, 'dist/livefire.workflow.js')
await writeFile(outPath, out, 'utf8')
console.log(`wrote ${outPath} (${out.length} bytes)`)
